"""Retro helper for Claude Code sessions.

  retro.py session [<id>] [--anyway]  open a retro on a session (default: the current one): print its
                                       session-log file (written when missing or stale) and its retro folder,
                                       holding the session's transcript.txt; a retro session only with --anyway
  retro.py render <retro-folder>       write its retro.md from retro.yaml and its session's session-log file
  retro.py pending [--all]             the session logs no retro has read, minus those the triage judged skip
                                       (--all keeps them)
  retro.py due                         "<count> <id>": today's worth sessions no retro names, and the first of
                                       them in the triage file's order; nothing when there is none
  retro.py check [--all] [folder]      the findings still to fix, of every retro or of that folder only
  retro.py validate <retro-folder>     check its retro.yaml, and that its session is the full id of a session-log
                                       file
  retro.py triage <session.yaml>...    judge session-log files worth a retro or not, into the day's triage file
  retro.py triage --hook               the same for the paths on stdin, piped after `sessions.py extract --hook
                                       --print-path` in the SessionEnd hook; never fails

session, pending, due, triage, and check without a folder, read config.yaml beside this skill's SKILL.md (see config.example.yaml), or --config.
Every file is read and written as UTF-8, whatever the locale.
"""
import argparse
import os
import re
import subprocess
import sys
import time
import unicodedata
from collections import Counter
from datetime import date, datetime, timezone
from pathlib import Path

try:
    import yaml
except ImportError:
    print("retro.py needs PyYAML: pip install pyyaml", file=sys.stderr)
    # The SessionEnd hook must never fail the session's exit.
    sys.exit(0 if "--hook" in sys.argv else 1)

# The improvement categories of a retro finding, after the installed retro skill.
CATEGORIES = {"navigation": "Navigation", "automated-checks": "Automated checks",
              "coding-standards": "Coding standards", "global-agents-md": "Global AGENTS.md",
              "tool-economy": "Tool economy", "no-ops": "No-ops", "information-access": "Information access"}
GENERATED_NOTE = ("<!-- Generated by retro.py render from retro.yaml and its session's session-log file: "
                  "edit retro.yaml, then render again. -->")
# Triage rules: each reads one value off a session-log file; a rule fires when the value reaches its limit.
TRIAGE_RULES = {
    "failures": lambda s: sum(len(v) for v in (s.get("failures") or {}).values()),
    "repeats": lambda s: len(s.get("repeats") or []),
    "search_streaks": lambda s: len(s.get("search_streaks") or []),
    "compactions": lambda s: len(s.get("compactions") or []),
    "interruptions": lambda s: s.get("interruptions") or 0,
    "denials": lambda s: sum((s.get("denials") or {}).values()),
    "api_errors": lambda s: sum((s.get("api_errors") or {}).values()),
    "active_s": lambda s: s.get("active_s") or 0,
    "cost_usd": lambda s: s.get("cost_usd"),                  # null when a model has no known price
}
# The day file's lock: how long a writer waits for it, and the age at which a lock left by a dead writer is taken.
LOCK_WAIT_S = 3
LOCK_STALE_S = 15                    # past the SessionEnd hook's 10-second timeout


SESSION_LOG = Path(__file__).resolve().parents[2] / "session-log" / "scripts" / "sessions.py"
NO_SESSION = "no session: name one, or run inside a Claude Code session"
ONE_SESSION = "a retro reads one session"
RETRO_SKILL = "retro-report"
RETRO_SESSION = "retro session"
# A finding's evidence: each item names a call (the transcript's #n) or a moment (at), with a short excerpt.
EXCERPT_LINES = 3
EXCERPT_CHARS = 300
AT_FORM = "must be a timestamp with a timezone (2026-11-17T13:12:42Z)"
CREATED_FORM = "must be a date-time with a timezone (2026-11-14T08:39:00-03:00)"
SEVERITIES = ("high", "medium", "low")
# A finding is written reviewing as soon as it is found; the user's reply (or a later verifier) settles it.
STATUSES = ("reviewing", "accepted", "wontfix")


class SessionLogError(Exception):
    """session-log could not give a session's file; the message is its own one-line reason."""


def metrics_path(name):
    """The path of a session's session-log file, for a session id or prefix: sessions.py extract writes it when
    missing or stale. SessionLogError carries session-log's error line."""
    lines = session_log("extract", name, "--print-path").splitlines()
    if not lines:
        raise SessionLogError(f"session-log printed no file for {name}")
    return Path(lines[0])


def session_log(*args):
    """The stdout of sessions.py <args>; SessionLogError carries session-log's error line."""
    done = subprocess.run([sys.executable, str(SESSION_LOG), *args],
                          capture_output=True, text=True, encoding="utf-8", errors="replace")
    if done.returncode:
        errors = done.stderr.strip().splitlines()
        raise SessionLogError(errors[-1] if errors else f"session-log {args[0]} failed for {args[1]}")
    return done.stdout


def slug(title, limit=50):
    """A folder slug from a session title: ASCII, lower case, words joined by '-', cut at a word to limit."""
    text = unicodedata.normalize("NFKD", title or "").encode("ascii", "ignore").decode().lower()
    out = ""
    for word in re.findall(r"[a-z0-9]+", text):
        if out and len(out) + 1 + len(word) > limit:
            break
        out = f"{out}-{word}" if out else word[:limit]
    return out


def retro_folder(retros_dir, metrics):
    """The folder of a session's retro: the one whose retro.yaml names it, else <retros>/<today>-<slug of its
    title, or the id's first 8 characters>."""
    for path in sorted(retros_dir.glob("*/retro.yaml")):
        retro = _load(path, [])
        if isinstance(retro, dict) and retro.get("session") == metrics["session"]:
            return path.parent
    name = slug(metrics.get("title")) or metrics["session"][:8]
    return retros_dir / f"{date.today():%Y-%m-%d}-{name}"


def is_retro_session(metrics):
    """Whether a session started with /retro-report: reading it would review a review."""
    start = metrics.get("start_skill")
    return isinstance(start, dict) and start.get("name") == RETRO_SKILL


def open_retro(cfg, name, anyway=False):
    """A session's session-log file and its retro folder, created when missing, with transcript.txt written
    (again) from session-log; or SessionLogError, nothing created. A retro session needs anyway."""
    path = metrics_path(name)
    errors = []
    metrics = _load(path, errors, str(path))
    if errors or not isinstance(metrics, dict) or not _is_text(metrics.get("session")):
        raise SessionLogError(errors[0] if errors else f"{path}: no session id")
    if is_retro_session(metrics) and not anyway:
        raise SessionLogError(f"{metrics['session']} started with /{RETRO_SKILL}: a {RETRO_SESSION}; "
                              "run again with --anyway to read it")
    text = session_log("transcript", metrics["session"])
    folder = retro_folder(cfg["retros"], metrics)
    folder.mkdir(exist_ok=True)
    (folder / "transcript.txt").write_text(text, encoding="utf-8", newline="\n")
    return path, folder


def _time(ts):
    return datetime.fromisoformat(ts.replace("Z", "+00:00"))


def _is_text(v):
    return isinstance(v, str) and bool(v.strip())


def _is_text_list(v):
    return isinstance(v, list) and all(_is_text(x) for x in v)


def _is_id(v):
    return isinstance(v, int) and not isinstance(v, bool)


def _at(v):
    """An evidence at as a timezone-aware datetime (YAML gives one unquoted, a string quoted), else None."""
    if isinstance(v, str):
        try:
            v = _time(v)
        except ValueError:
            return None
    return v if isinstance(v, datetime) and v.tzinfo is not None else None


def _field(data, key, check, problem, errors, label=None, required=True):
    if key not in data:
        if required:
            errors.append(f"{label or key}: missing")
    elif not check(data[key]):
        errors.append(f"{label or key}: {problem}")


def _is_number(v):
    return isinstance(v, (int, float)) and not isinstance(v, bool) and v > 0


def _triage_errors(triage):
    """The problems of config.yaml's triage block."""
    if not isinstance(triage, dict):
        return ["triage: must be a mapping with min_calls and limits"]
    errors = []
    _field(triage, "min_calls", lambda v: type(v) is int and v > 0, "must be a positive whole number", errors,
           "triage.min_calls")
    limits = triage.get("limits")
    if not isinstance(limits, dict):
        errors.append("triage.limits: must be a mapping of rule to limit")
        return errors
    for rule, limit in limits.items():
        if rule not in TRIAGE_RULES:
            errors.append(f"triage.limits.{rule}: not a rule ({', '.join(TRIAGE_RULES)})")
        elif not _is_number(limit):
            errors.append(f"triage.limits.{rule}: must be a positive number")
    return errors


def _load(path, errors, label=None):
    label = label or path.name
    if not path.is_file():
        errors.append(f"{label}: missing")
        return None
    try:
        return yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as e:
        errors.append(f"{label}: not valid YAML: {str(e).splitlines()[0]}")
        return None


def _in(folder, errors):
    """Errors of one retro, named by its folder."""
    return [f"{folder.name}: {e}" for e in errors]


def _fail(errors):
    """Print the errors; true when there were any."""
    for e in errors:
        print(e, file=sys.stderr)
    return bool(errors)


def _excerpt_errors(item, label):
    """An evidence item's excerpt problems: missing, not text, or past the line or character limit."""
    errors = []
    _field(item, "excerpt", _is_text, "must be text", errors, label)
    if not errors:
        text = item["excerpt"].strip()
        lines = text.splitlines()
        if len(lines) > EXCERPT_LINES:
            errors.append(f"{label}: {len(lines)} lines, at most {EXCERPT_LINES}")
        if len(text) > EXCERPT_CHARS:
            errors.append(f"{label}: {len(text)} characters, at most {EXCERPT_CHARS}")
    return errors


def evidence_errors(f, name):
    """The shape problems of a finding's evidence; its bounds need the session's metrics (bound_errors)."""
    evidence = f.get("evidence")
    if "evidence" not in f:
        return [f"{name}.evidence: missing"]
    if not isinstance(evidence, list) or not evidence:
        return [f"{name}.evidence: must be a non-empty list"]
    errors = []
    for k, item in enumerate(evidence, 1):
        label = f"{name}.evidence[#{k}]"
        if not isinstance(item, dict):
            errors.append(f"{label}: must be a mapping")
            continue
        if ("call" in item) == ("at" in item):
            errors.append(f"{label}: needs call or at, not both")
        _field(item, "call", lambda v: _is_id(v) and v > 0, "must be a positive whole number", errors,
               f"{label}.call", required=False)
        _field(item, "at", lambda v: _at(v) is not None, AT_FORM, errors, f"{label}.at", required=False)
        errors += _excerpt_errors(item, f"{label}.excerpt")
    return errors


def _utc_iso(moment):
    """A timezone-aware datetime as UTC ISO text with Z, the form of a session-log file's start and end."""
    return moment.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def bound_errors(findings, metrics):
    """The evidence of valid findings that lies outside their session: a call past calls.total, an at before
    start or after end of its session-log file."""
    total = (metrics.get("calls") or {}).get("total", 0)
    start, end = _at(metrics.get("start")), _at(metrics.get("end"))
    errors = []
    for f in findings:
        for k, item in enumerate(f["evidence"], 1):
            label = f"findings[{f['id']}].evidence[#{k}]"
            if "call" in item and item["call"] > total:
                errors.append(f"{label}.call: {item['call']} is past the session's {total} calls")
            elif "at" in item and not (start and end and start <= _at(item["at"]) <= end):
                span = (f"{_utc_iso(start)} to {_utc_iso(end)}" if start and end
                        else "the session-log file has no start and end")
                errors.append(f"{label}.at: {_utc_iso(_at(item['at']))} is outside the session ({span})")
    return errors


def finding_errors(findings):
    """Each finding's problems, the finding named by its id, or by #position when its id is unusable."""
    errors, ids = [], set()
    for pos, f in enumerate(findings, 1):
        if not isinstance(f, dict):
            errors.append(f"findings[#{pos}]: must be a mapping")
            continue
        fid = f.get("id")
        name = f"findings[{fid}]" if _is_id(fid) else f"findings[#{pos}]"
        if _is_id(fid) and fid in ids:
            errors.append(f"{name}.id: used twice")
        else:
            _field(f, "id", _is_id, "must be an integer", errors, f"{name}.id")
        if _is_id(fid):
            ids.add(fid)
        _field(f, "category", lambda v: v in CATEGORIES,
               f"{f.get('category')!r} is not one of {', '.join(CATEGORIES)}", errors, f"{name}.category")
        _field(f, "severity", lambda v: v in SEVERITIES, f"must be one of {', '.join(SEVERITIES)}", errors,
               f"{name}.severity")
        _field(f, "status", lambda v: v in STATUSES, f"must be one of {', '.join(STATUSES)}", errors,
               f"{name}.status")
        for key in ("what", "fix", "lands_in"):
            _field(f, key, _is_text, "must be text", errors, f"{name}.{key}")
        errors += evidence_errors(f, name)
        for key in ("feature", "wontfix"):
            _field(f, key, _is_text, "must be text", errors, f"{name}.{key}", required=False)
        if "sessions" in f:
            errors.append(f"{name}.sessions: not used ({ONE_SESSION})")
        status = f.get("status")
        if status == "wontfix" and "wontfix" not in f:
            errors.append(f"{name}.wontfix: missing (the reason, as status is wontfix)")
        if "wontfix" in f and status in STATUSES and status != "wontfix":
            errors.append(f"{name}.wontfix: only on a finding whose status is wontfix")
        if "feature" in f and status in STATUSES and status != "accepted":
            errors.append(f"{name}.feature: only on an accepted finding")
    return errors


def retro_errors(retro):
    """The problems of a parsed retro.yaml, each as '<field>: <problem>'."""
    if not isinstance(retro, dict):
        return ["must be a mapping"]
    errors = []
    _field(retro, "created", lambda v: _at(v) is not None, CREATED_FORM, errors)
    if "date" in retro:
        errors.append("date: replaced by created, a date-time with its timezone")
    for key in ("title", "summary"):
        _field(retro, key, _is_text, "must be text", errors)
    _field(retro, "session", _is_text, "must be a session id", errors)
    if "sources" in retro:
        errors.append(f"sources: replaced by session ({ONE_SESSION})")
    _field(retro, "findings", lambda v: isinstance(v, list), "must be a list", errors)
    _field(retro, "decisions", _is_text_list, "must be a list of text", errors)
    _field(retro, "outcome", _is_text, "must be text", errors, required=False)
    if isinstance(retro.get("findings"), list):
        errors += finding_errors(retro["findings"])
    return errors


def session_metrics(session):
    """The session-log file of a retro's session, parsed, and its problems: session-log's own error line, or
    a session that is not the full id the file names."""
    try:
        path = metrics_path(session)
    except SessionLogError as e:
        return None, [str(e)]
    errors = []
    metrics = _load(path, errors, str(path))
    if errors:
        return None, errors
    found = metrics.get("session") if isinstance(metrics, dict) else None
    if found != session:
        return None, [f"{session} is not a full session id (session-log has {found})"]
    return metrics, []


def read_retro(folder):
    """A retro folder's retro.yaml, parsed, with its problems one line each."""
    errors = []
    retro = _load(Path(folder) / "retro.yaml", errors)
    if not errors:
        errors += [f"retro.yaml: {e}" for e in retro_errors(retro)]
    return retro, errors


def _cell(text):
    return " ".join(str(text).split()).replace("|", "\\|")


def _row(cells):
    return "| " + " | ".join(_cell(c) for c in cells) + " |"


def _fix(f):
    if "wontfix" in f:
        return f"{f['fix'].strip().rstrip('.')}. Won't fix: {f['wontfix']}"
    return f"{f['fix']} ({f['feature']})" if "feature" in f else f["fix"]


def _evidence(f):
    """A finding's evidence as references: #<call>, or an at's UTC time as the transcript prints it."""
    return ", ".join(f"#{e['call']}" if "call" in e else _utc_iso(_at(e["at"]))[11:19] for e in f["evidence"])


def _session_row(metrics):
    cost = metrics.get("cost_usd")
    return _row([metrics["session"][:8], Path(metrics["project"]).name if metrics.get("project") else "-",
                 round((metrics.get("duration_s") or 0) / 60), (metrics.get("calls") or {}).get("total", 0),
                 sum(len(v) for v in (metrics.get("failures") or {}).values()),
                 len(metrics.get("search_streaks") or []), f"${cost:.2f}" if cost is not None else "-"])


def report(retro, metrics, statuses):
    """retro.md for a valid retro: Source, Findings with their statuses, Decisions, its session's row from the
    session-log file and, when written, Outcome."""
    lines = [GENERATED_NOTE, f"# Retro {_at(retro['created']):%Y-%m-%d %H:%M}: {retro['title']}", "",
             f"Source: {retro['summary'].strip()}", "", "## Findings", "",
             "| # | Category | Severity | What happened | Evidence | Fix | Lands in | Status |",
             "|---|---|---|---|---|---|---|---|"]
    lines += [_row([f["id"], CATEGORIES[f["category"]], f["severity"], f["what"], _evidence(f), _fix(f),
                    f["lands_in"], status])
              for f, status in zip(retro["findings"], statuses)]
    if retro["decisions"]:
        lines += ["", "## Decisions", ""] + [f"- {d.strip()}" for d in retro["decisions"]]
    lines += ["", "## Sessions", "", "| Session | Project | Minutes | Calls | Failures | Search streaks | Cost |",
              "|---|---|---|---|---|---|---|", _session_row(metrics)]
    if "outcome" in retro:
        lines += ["", "## Outcome", "", retro["outcome"].strip()]
    return "\n".join(lines) + "\n"


def load_config(path):
    """retros and projects from config.yaml, ~ expanded, with one line per problem."""
    errors = []
    cfg = _load(path, errors)
    if not errors:
        if not isinstance(cfg, dict):
            errors.append("must be a mapping")
        else:
            _field(cfg, "retros", _is_text, "must be a path", errors)
            _field(cfg, "projects", lambda v: _is_text_list(v) and v, "must be a list of paths", errors)
            if _is_text(cfg.get("retros")) and not Path(cfg["retros"]).expanduser().is_dir():
                errors.append(f"retros: {Path(cfg['retros']).expanduser()} is not a folder")
    if errors:
        return None, [_config_error(path, e) for e in errors]
    return {"retros": Path(cfg["retros"]).expanduser(),
            "projects": [Path(p).expanduser() for p in cfg["projects"]],
            "triage": cfg.get("triage")}, []


def _config_error(path, error):
    return f"{path}: {error.removeprefix(path.name + ': ')}; see config.example.yaml"


def load_triage_config(path):
    """load_config plus its triage block, which only triage requires; or None and one line per problem."""
    cfg, errors = load_config(path)
    if cfg:
        errors = ["triage: missing"] if cfg["triage"] is None else _triage_errors(cfg["triage"])
        errors = [_config_error(path, e) for e in errors]
    return (None if errors else cfg), errors


def read_retros(cfg):
    """Every retro folder under retros, parsed; its validate errors prefixed by the folder name."""
    retros, errors = [], []
    for folder in sorted(p.parent for p in cfg["retros"].glob("*/retro.yaml")):
        retro, problems = read_retro(folder)
        errors += _in(folder, problems)
        retros.append((folder, retro))
    return retros, errors


def session_folder(project):
    """The folder Claude Code keeps a project's session logs in: its path with each non-alphanumeric as '-'."""
    return re.sub(r"[^A-Za-z0-9]", "-", str(project))


def skipped_sessions(retros):
    """The sessions the triage judged skip, read from every day file under <retros>/triage; and one line per
    broken day file."""
    skipped, errors = set(), []
    for path in sorted((retros / "triage").glob("*-triage.yaml")):
        try:
            skipped |= {e["session"] for e in _entries(path)
                        if e.get("verdict") == "skip" and isinstance(e.get("session"), str)}
        except ValueError as e:
            errors.append(str(e))
    return skipped, errors


def pending_logs(cfg, retros, skipped=frozenset()):
    """Top-level session logs of the configured projects and their subfolders, oldest first, minus the sessions
    a retro names, the sessions in skipped and the session in progress."""
    used = {retro["session"] for _, retro in retros} | set(skipped)
    used.add(os.environ.get("CLAUDE_CODE_SESSION_ID"))
    folders = [f for f in (Path.home() / ".claude" / "projects").glob("*") if in_folders(f.name, cfg["projects"])]
    logs = [log for f in folders for log in f.glob("*.jsonl") if log.stem not in used]
    return sorted(logs, key=lambda log: log.stat().st_mtime)


def due_sessions(cfg, retros):
    """Today's worth sessions, in the order of today's triage file, minus the sessions a retro names and the
    session in progress; and one line when that file is broken."""
    used = {retro["session"] for _, retro in retros} | {os.environ.get("CLAUDE_CODE_SESSION_ID")}
    try:
        entries = _entries(cfg["retros"] / "triage" / f"{date.today():%Y-%m-%d}-triage.yaml")
    except ValueError as e:
        return [], [str(e)]
    return [e["session"] for e in entries
            if e.get("verdict") == "worth" and isinstance(e.get("session"), str) and e["session"] not in used], []


def in_folders(name, projects):
    """True when a session folder name is the folder of one of projects or of a subfolder."""
    return any(name == n or name.startswith(n + "-") for n in map(session_folder, projects))


def _fmt_number(v):
    return str(round(v, 2)) if isinstance(v, float) else str(v)


def judge(session, triage):
    """("worth" | "skip", reasons): skip a retro session or below min_calls, else worth when any rule reaches
    its limit."""
    if is_retro_session(session):
        return "skip", [RETRO_SESSION]
    calls = session["calls"]["total"]
    if calls < triage["min_calls"]:
        return "skip", [f"calls {calls} < {triage['min_calls']}"]
    reasons = []
    for rule, value_of in TRIAGE_RULES.items():
        limit = triage["limits"].get(rule)
        value = value_of(session)
        if limit is not None and value is not None and value >= limit:
            reasons.append(f"{rule} {_fmt_number(value)} >= {_fmt_number(limit)}")
    return ("worth" if reasons else "skip"), reasons


def triage_file(retros, start):
    """<retros>/triage/<local date of the session's start>-triage.yaml, the day session-log files it under."""
    return retros / "triage" / f"{_time(start).astimezone():%Y-%m-%d}-triage.yaml"


def _lock(lock):
    """Create lock, waiting up to LOCK_WAIT_S while another writer holds it; a lock older than LOCK_STALE_S
    was left by a writer that died, and is taken. Raises ValueError when it stays held."""
    deadline = time.monotonic() + LOCK_WAIT_S
    while True:
        try:
            os.close(os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY))
            return
        except FileExistsError:
            try:
                if time.time() - lock.stat().st_mtime > LOCK_STALE_S:
                    lock.unlink()
                    continue
            except FileNotFoundError:
                continue
            if time.monotonic() >= deadline:
                raise ValueError(f"{lock.with_suffix('')}: locked by another writer for {LOCK_WAIT_S}s") from None
        except PermissionError:
            # Windows refuses to create a file while its deletion by another writer is pending: try again.
            if time.monotonic() >= deadline:
                raise
        time.sleep(0.05)


def _entries(path):
    """The entries of a day file; ValueError when it is not a list of mappings."""
    if not path.exists():
        return []
    try:
        entries = yaml.safe_load(path.read_text(encoding="utf-8")) or []
    except OSError as e:
        raise ValueError(f"{path}: cannot read: {e}") from None
    except yaml.YAMLError as e:
        raise ValueError(f"{path}: not valid YAML: {str(e).splitlines()[0]}") from None
    if not (isinstance(entries, list) and all(isinstance(e, dict) for e in entries)):
        raise ValueError(f"{path}: not a list of triage entries")
    return entries


def _replace(tmp, path):
    """os.replace, tried again for up to LOCK_WAIT_S while it is refused: on Windows a file cannot be replaced
    while a reader (pending, due) has it open."""
    deadline = time.monotonic() + LOCK_WAIT_S
    while True:
        try:
            os.replace(tmp, path)
            return
        except PermissionError:
            if time.monotonic() >= deadline:
                raise
            time.sleep(0.05)


def record(path, entry):
    """Put entry in the day file, in place of an earlier entry of the same session. Sessions ending together
    write the same file, so the read and the write hold its lock, and the file is replaced whole. Every failure
    is a ValueError naming the file."""
    lock = path.with_name(path.name + ".lock")
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        _lock(lock)
    except OSError as e:
        raise ValueError(f"{path}: cannot lock: {e}") from None
    try:
        entries = [e for e in _entries(path) if e.get("session") != entry["session"]] + [entry]
        tmp = path.with_name(path.name + ".tmp")
        tmp.write_text(yaml.safe_dump(entries, sort_keys=False, allow_unicode=True, width=200), encoding="utf-8")
        _replace(tmp, path)
    except OSError as e:
        tmp.unlink(missing_ok=True)
        raise ValueError(f"{path}: cannot write: {e}") from None
    finally:
        try:
            lock.unlink(missing_ok=True)         # gone when a writer took it as stale
        except OSError:
            pass


def triage_session(cfg, path):
    """Judge one session-log file and record it; the line to print. Raises ValueError for a file it cannot judge."""
    try:
        session = yaml.safe_load(Path(path).read_text(encoding="utf-8"))
        sid, project = session["session"], session["project"]
        if not in_folders(session_folder(Path(project)), cfg["projects"]):
            return f"{sid} not judged: {project} is not in projects"
        verdict, reasons = judge(session, cfg["triage"])
        day = triage_file(cfg["retros"], session["start"])
    except (OSError, yaml.YAMLError, KeyError, TypeError, ValueError, AttributeError) as e:
        raise ValueError(f"{path}: not a session-log file ({e.__class__.__name__}: {str(e).splitlines()[0]})") from None
    record(day, {"session": sid, "project": project, "title": session.get("title"), "verdict": verdict,
                 "reasons": reasons, "judged": date.today().isoformat()})
    return f"{sid} {verdict}" + (f": {'; '.join(reasons)}" if reasons else "")


def triage(cfg, paths):
    """Judge each named session-log file; one line per file, errors to stderr. Exit 1 when any failed."""
    failed = False
    for path in paths:
        try:
            print(triage_session(cfg, path))
        except ValueError as e:
            print(e, file=sys.stderr)
            failed = True
    return 1 if failed else 0


def triage_hook(config):
    """SessionEnd hook: judge the session-log files whose paths come on stdin (none when the extract failed).
    Every failure is one stderr line and exit 0, so ending a session never blocks."""
    try:
        paths = [line.strip() for line in sys.stdin if line.strip()]
        cfg, errors = load_triage_config(config) if paths else (None, [])
    except Exception as exc:  # noqa: BLE001 - a hook must never fail the session's exit
        print(f"retro-report triage hook: {exc!r}", file=sys.stderr)
        return 0
    if errors:
        print(f"retro-report triage hook: {errors[0]}", file=sys.stderr)
        return 0
    for path in paths:
        try:
            print(triage_session(cfg, path))
        except ValueError as exc:                # a file it cannot judge or record, already one line
            print(f"retro-report triage hook: {exc}", file=sys.stderr)
        except Exception as exc:  # noqa: BLE001 - one session's failure leaves the others judged
            print(f"retro-report triage hook: {exc!r}", file=sys.stderr)
    return 0


def finding_statuses(folder, findings):
    """Each finding's status, read from the retro's roadmap.yaml and the feature.yaml files under features/:
    reviewing and wontfix as written; an accepted one open (no feature), fixed (its feature is done) or planned.
    No statuses when a file is broken."""
    errors = []
    roadmap = _load(folder / "roadmap.yaml", errors) if (folder / "roadmap.yaml").is_file() else {"milestones": []}
    if not errors and not (isinstance(roadmap, dict) and isinstance(roadmap.get("milestones"), list)):
        errors.append("roadmap.yaml: must be a mapping with milestones")
    done = set()
    for path in sorted(folder.glob("features/*/feature.yaml")):
        feature = _load(path, errors, path.relative_to(folder).as_posix())
        if isinstance(feature, dict) and feature.get("status") == "done":
            done.add(feature.get("roadmap"))
    if errors:
        return [], errors
    listed = {f.get("id") for m in roadmap["milestones"] if isinstance(m, dict)
              for f in m.get("features") or [] if isinstance(f, dict)}
    statuses = []
    for f in findings:
        if f["status"] != "accepted":
            statuses.append(f["status"])
        elif "feature" not in f:
            statuses.append("open")
        else:
            if f["feature"] not in listed:
                errors.append(f"findings[{f['id']}]: {f['feature']} is not in roadmap.yaml")
            statuses.append("fixed" if f["feature"] in done else "planned")
    return statuses, errors


def check(retros, show_all):
    """Lines for the findings still to do (every finding with show_all) and a closing count; and the errors."""
    lines, errors, count = [], [], Counter()
    for folder, retro in retros:
        statuses, problems = finding_statuses(folder, retro["findings"])
        errors += _in(folder, problems)
        for f, status in zip(retro["findings"], statuses):
            count[status] += 1
            if show_all or status in ("open", "planned"):
                lines.append(f"{folder.name} #{f['id']} {status}: {' '.join(_fix(f).split())}")
    lines.append(f"{count['open'] + count['planned']} to do; {count['reviewing']} reviewing, {count['fixed']} fixed, "
                 f"{count['wontfix']} won't fix")
    return lines, errors


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", type=Path, default=Path(__file__).resolve().parent.parent / "config.yaml",
                        help="config.yaml to read (default: the one beside SKILL.md)")
    sub = parser.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("session", help="open a retro on a session, the current one by default: print its session-log "
                                       "file and its retro folder, holding transcript.txt")
    s.add_argument("id", nargs="?", help="a session id or prefix (default: CLAUDE_CODE_SESSION_ID)")
    s.add_argument("--anyway", action="store_true", help="open a retro on a session that started with /retro-report")
    v = sub.add_parser("validate", help="check a retro folder's retro.yaml against its session's session-log file")
    v.add_argument("folder")
    r = sub.add_parser("render", help="write a valid retro folder's retro.md")
    r.add_argument("folder")
    pending_parser = sub.add_parser("pending", help="list the session logs no retro has read nor the triage judged skip, oldest first")
    pending_parser.add_argument("--all", action="store_true", help="also list the sessions the triage judged skip")
    sub.add_parser("due", help="print the count of today's worth sessions no retro names and the first id, else nothing")
    c = sub.add_parser("check", help="list the findings still to fix, of every retro or of one folder")
    c.add_argument("folder", nargs="?", help="check this retro folder only (no config needed)")
    c.add_argument("--all", action="store_true", help="also list the reviewing, fixed and wontfix findings")
    t = sub.add_parser("triage", help="judge session-log files worth a retro or not, into the day's triage file")
    t.add_argument("sessions", nargs="*", help="session-log files (<out>/<date>/<session>.yaml)")
    t.add_argument("--hook", action="store_true",
                   help="SessionEnd hook: read the files from stdin, one path per line; never exit non-zero")
    args = parser.parse_args(argv)
    if args.cmd == "triage" and args.hook == bool(args.sessions):
        parser.error("triage takes session files, or --hook and their paths on stdin")

    if args.cmd == "session":
        name = args.id or os.environ.get("CLAUDE_CODE_SESSION_ID")
        if not name:
            return _fail([NO_SESSION])
        cfg, errors = load_config(args.config)
        if _fail(errors):
            return 1
        try:
            path, folder = open_retro(cfg, name, args.anyway)
        except SessionLogError as e:
            return _fail([str(e)])
        print(path)
        print(folder)
        return 0
    if args.cmd == "triage" and args.hook:
        return triage_hook(args.config)
    if args.cmd == "triage":
        cfg, errors = load_triage_config(args.config)
        if _fail(errors):
            return 1
        return triage(cfg, args.sessions)
    if args.cmd in ("pending", "due", "check"):
        cfg = None
        if args.cmd == "check" and args.folder:
            retro, errors = read_retro(args.folder)
            retros = [(Path(args.folder), retro)]
        else:
            cfg, errors = load_config(args.config)
            retros, retro_problems = read_retros(cfg) if cfg else ([], [])
            errors += retro_problems
        skipped, sessions = set(), []
        if cfg and args.cmd == "pending" and not args.all:
            skipped, triage_problems = skipped_sessions(cfg["retros"])
            errors += triage_problems
        elif cfg and args.cmd == "due":
            sessions, triage_problems = due_sessions(cfg, retros)
            errors += triage_problems
        if _fail(errors):
            return 1
        if args.cmd == "pending":
            lines = [str(log) for log in pending_logs(cfg, retros, skipped)]
        elif args.cmd == "due":
            lines = [f"{len(sessions)} {sessions[0]}"] if sessions else []
        else:
            lines, errors = check(retros, args.all)
            if _fail(errors):
                return 1
        for line in lines:
            print(line)
        return 0
    retro, errors = read_retro(args.folder)
    if not errors:
        metrics, problems = session_metrics(retro["session"])
        errors = [f"retro.yaml: session: {e}" for e in problems]
        if metrics:
            errors += [f"retro.yaml: {e}" for e in bound_errors(retro["findings"], metrics)]
    if _fail(errors):
        return 1
    if args.cmd == "validate":
        print(f"{args.folder} OK")
        return 0
    folder = Path(args.folder)
    statuses, errors = finding_statuses(folder, retro["findings"])
    if _fail(errors):
        return 1
    (folder / "retro.md").write_text(report(retro, metrics, statuses), encoding="utf-8")
    print(f"wrote {folder / 'retro.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
