"""Retro helper for Claude Code sessions.

  retro.py digest <session.jsonl>...   each session's calls, failures, repeats and cost, as a YAML list
  retro.py render <retro-folder>       write its retro.md from the two yaml files
  retro.py pending                     the session logs no retro has read
  retro.py check [--all]               the findings of every retro still to fix
  retro.py validate <retro-folder>     check its retro.yaml, and that sessions.yaml digests each session it names

pending and check read config.yaml beside this skill's SKILL.md (see config.example.yaml), or --config.
"""
import argparse
import json
import os
import re
import sys
from collections import Counter
from datetime import date, datetime
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("retro.py needs PyYAML: pip install pyyaml")

# Error classes read off a result's text, after tokeneconomizer's observe.py; first match wins.
ERROR_PATTERNS = [
    ("command_missing", re.compile(r"command not found|: not found$|is not recognized as")),
    ("module_missing", re.compile(r"ModuleNotFoundError|No module named|Cannot find module", re.I)),
    ("file_missing", re.compile(r"No such file or directory|File does not exist|ENOENT", re.I)),
    ("permission_denied", re.compile(r"Permission denied|EACCES|Operation not permitted", re.I)),
]
LINE_MAX = 200
INPUT_MAX = 120
STREAK_MIN = 3
# Search tools, each with the input field that names what it searched.
SEARCH_TOOL_FIELD = {"Grep": "pattern", "Glob": "pattern", "Read": "file_path"}
SEARCH_HEADS = {"grep", "rg", "find", "ls", "cat", "head", "tail", "sed", "wc"}
# Commands that neither search nor change anything: they keep a shell search a search.
NEUTRAL_HEADS = {"cd", "echo", "sort", "uniq", "xargs", "true"}
# Shell words followed by a command; the command is the segment's head.
PREFIX_WORDS = {"do", "then", "else", "if"}
# Shell words whose segment runs no command of its own.
SKIP_WORDS = {"for", "done", "fi"}
SEGMENT_SPLIT = re.compile(r"&&|\|\||;|\||\n")
# A redirect to a file; /dev/null and &N are not writes.
WRITE_REDIRECT = re.compile(r">>?\s*(?!/dev/null\b|&)\S")
WRITE_FLAGS = {"-i", "-delete"}
# The improvement categories of a retro finding, after the installed retro skill.
CATEGORIES = {"navigation": "Navigation", "automated-checks": "Automated checks",
              "coding-standards": "Coding standards", "global-agents-md": "Global AGENTS.md",
              "tool-economy": "Tool economy", "no-ops": "No-ops", "information-access": "Information access"}
GENERATED_NOTE = ("<!-- Generated by retro.py render from retro.yaml and sessions.yaml: "
                  "edit those, then render again. -->")
TOKEN_FIELDS = {"input": "input_tokens", "output": "output_tokens",
                "cache_read": "cache_read_input_tokens", "cache_write": "cache_creation_input_tokens"}


class NotASessionLog(Exception):
    pass


def read_records(path):
    """The JSON records of a session log; raises NotASessionLog when it holds no message."""
    path = Path(path)
    if not path.is_file():
        raise NotASessionLog(path)
    records = []
    for line in path.read_text(errors="replace").splitlines():
        try:
            rec = json.loads(line)
        except ValueError:
            continue
        if isinstance(rec, dict):
            records.append(rec)
    if not any(r.get("type") in ("user", "assistant") and isinstance(r.get("message"), dict) for r in records):
        raise NotASessionLog(path)
    return records


def calls(records):
    """Ordered tool calls: {n, tool, input, result, is_error}, results paired by tool_use id."""
    out, by_id = [], {}
    for rec in records:
        content = (rec.get("message") or {}).get("content")
        if not isinstance(content, list):
            continue
        for block in content:
            if block.get("type") == "tool_use":
                call = {"n": len(out) + 1, "tool": block.get("name"), "input": block.get("input") or {},
                        "result": "", "is_error": False}
                out.append(call)
                by_id[block.get("id")] = call
            elif block.get("type") == "tool_result" and block.get("tool_use_id") in by_id:
                call = by_id[block["tool_use_id"]]
                call["result"] = result_text(block.get("content"))
                call["is_error"] = bool(block.get("is_error"))
    return out


def result_text(content):
    if isinstance(content, list):
        return "\n".join(b.get("text", "") for b in content if isinstance(b, dict))
    return content if isinstance(content, str) else ""


def failures(call_list):
    """Calls grouped by error class: a line matching a pattern, else `other` when the tool said is_error.

    Only shell output and results marked is_error are scanned: a Read of a file that quotes an error is no failure."""
    out = {}
    for c in call_list:
        if c["tool"] != "Bash" and not c["is_error"]:
            continue
        lines = c["result"].splitlines()
        hit = next(((cls, line) for line in lines for cls, rx in ERROR_PATTERNS if rx.search(line)), None)
        if hit is None and c["is_error"]:
            hit = ("other", next((ln for ln in lines if ln.strip()), ""))
        if hit:
            cls, line = hit
            out.setdefault(cls, []).append({"call": c["n"], "tool": c["tool"], "line": line.strip()[:LINE_MAX]})
    order = [cls for cls, _ in ERROR_PATTERNS] + ["other"]
    return {cls: out[cls] for cls in order if cls in out}


def call_text(c):
    """What a call asked for, in one line: the command, the searched value, or the input as JSON."""
    if c["tool"] == "Bash":
        return str(c["input"].get("command", ""))
    key = SEARCH_TOOL_FIELD.get(c["tool"])
    if key and key in c["input"]:
        return f"{c['tool']} {c['input'][key]}"
    return json.dumps(c["input"], sort_keys=True)


def repeats(call_list):
    """Calls made more than once with identical input, in order of first use."""
    seen, first = Counter(), {}
    for c in call_list:
        key = (c["tool"], json.dumps(c["input"], sort_keys=True))
        seen[key] += 1
        first.setdefault(key, c)
    return [{"tool": key[0], "input": call_text(first[key])[:INPUT_MAX], "count": n}
            for key, n in seen.items() if n > 1]


def shell_heads(command):
    """The command each segment runs, past loop and if words; None for a segment that writes a file."""
    heads = []
    for seg in SEGMENT_SPLIT.split(command):
        words = seg.split()
        if WRITE_REDIRECT.search(seg) or WRITE_FLAGS & set(words):
            heads.append(None)
            continue
        while words and words[0] in PREFIX_WORDS:
            words = words[1:]
        if words and words[0] not in SKIP_WORDS:
            heads.append(words[0].lstrip("("))
    return heads


def is_search(c):
    if c["tool"] in SEARCH_TOOL_FIELD:
        return True
    if c["tool"] != "Bash":
        return False
    heads = shell_heads(call_text(c))
    return any(h in SEARCH_HEADS for h in heads) and all(h in SEARCH_HEADS | NEUTRAL_HEADS for h in heads)


def search_streaks(call_list):
    """Runs of STREAK_MIN or more search calls in a row."""
    runs, run = [], []
    for c in call_list + [None]:
        if c is not None and is_search(c):
            run.append(c)
            continue
        if len(run) >= STREAK_MIN:
            runs.append({"calls": [r["n"] for r in run], "commands": [call_text(r)[:INPUT_MAX] for r in run]})
        run = []
    return runs


def tokens(records):
    """Tokens summed once per message id: a message spread over several lines repeats its usage."""
    by_id = {}
    for rec in records:
        msg = rec.get("message") or {}
        if isinstance(msg.get("usage"), dict):
            by_id[msg.get("id") or id(rec)] = msg["usage"]
    return {k: sum(int(u.get(f) or 0) for u in by_id.values()) for k, f in TOKEN_FIELDS.items()}


def cost_usd(records):
    """The session's own total from its last cost-state record; None when it recorded none."""
    totals = [r["totalCostUSD"] for r in records if r.get("type") == "cost-state" and "totalCostUSD" in r]
    return totals[-1] if totals else None


def subagents(path):
    """Each subagent log beside the session (<session>/subagents/agent-<id>.jsonl), digested apart."""
    out = []
    for log in sorted((Path(path).parent / Path(path).stem / "subagents").glob("agent-*.jsonl")):
        try:
            records = read_records(log)
        except NotASessionLog:
            continue
        meta = log.with_suffix(".meta.json")
        try:
            description = json.loads(meta.read_text()).get("description") if meta.is_file() else None
        except ValueError:
            description = None
        out.append({"id": log.stem.removeprefix("agent-"), "description": description,
                    "calls": len(calls(records)), "tokens": tokens(records)})
    return out


def _time(ts):
    return datetime.fromisoformat(ts.replace("Z", "+00:00"))


def _iso(ts):
    return _time(ts).strftime("%Y-%m-%dT%H:%M:%SZ")


def digest(path):
    records = read_records(path)
    session = next((r["sessionId"] for r in records if r.get("sessionId")), Path(path).stem)
    project = next((r["cwd"] for r in records if r.get("cwd")), None)
    stamps = sorted((r["timestamp"] for r in records if r.get("timestamp")), key=_time)
    call_list = calls(records)
    return {
        "session": session,
        "project": project,
        "start": _iso(stamps[0]) if stamps else None,
        "end": _iso(stamps[-1]) if stamps else None,
        "duration_s": int((_time(stamps[-1]) - _time(stamps[0])).total_seconds()) if stamps else 0,
        "calls": {"total": len(call_list), "by_tool": dict(sorted(Counter(c["tool"] for c in call_list).items()))},
        "failures": failures(call_list),
        "repeats": repeats(call_list),
        "search_streaks": search_streaks(call_list),
        "tokens": tokens(records),
        "cost_usd": cost_usd(records),
        "subagents": subagents(path),
    }


def _is_text(v):
    return isinstance(v, str) and bool(v.strip())


def _is_text_list(v):
    return isinstance(v, list) and all(_is_text(x) for x in v)


def _is_id(v):
    return isinstance(v, int) and not isinstance(v, bool)


def _field(data, key, check, problem, errors, label=None, required=True):
    if key not in data:
        if required:
            errors.append(f"{label or key}: missing")
    elif not check(data[key]):
        errors.append(f"{label or key}: {problem}")


def _load(path, errors):
    if not path.is_file():
        errors.append(f"{path.name}: missing")
        return None
    try:
        return yaml.safe_load(path.read_text())
    except yaml.YAMLError as e:
        errors.append(f"{path.name}: not valid YAML: {str(e).splitlines()[0]}")
        return None


def _twice(ids):
    """The ids that appear more than once, in order of their first repeat."""
    seen, out = set(), []
    for i in ids:
        if i in seen and i not in out:
            out.append(i)
        seen.add(i)
    return out


def _sources(retro):
    """The session ids a retro names, or None when they are unusable."""
    src = retro.get("sources") if isinstance(retro, dict) else None
    named = src.get("sessions") if isinstance(src, dict) else None
    return named if _is_text_list(named) and named else None


def finding_errors(findings, named):
    """Each finding's problems, the finding named by its id, or by #position when its id is unusable."""
    errors, ids = [], set()
    for pos, f in enumerate(findings, 1):
        if not isinstance(f, dict):
            errors.append(f"findings[#{pos}]: must be a mapping")
            continue
        fid = f.get("id")
        name = f"findings[{fid}]" if _is_id(fid) else f"findings[#{pos}]"
        if _is_id(fid) and fid in ids:
            errors.append(f"{name}.id: used twice")
        else:
            _field(f, "id", _is_id, "must be an integer", errors, f"{name}.id")
        if _is_id(fid):
            ids.add(fid)
        _field(f, "category", lambda v: v in CATEGORIES,
               f"{f.get('category')!r} is not one of {', '.join(CATEGORIES)}", errors, f"{name}.category")
        for key in ("what", "fix"):
            _field(f, key, _is_text, "must be text", errors, f"{name}.{key}")
        for key in ("feature", "wontfix"):
            _field(f, key, _is_text, "must be text", errors, f"{name}.{key}", required=False)
        _field(f, "sessions", _is_text_list, "must be a list of text", errors, f"{name}.sessions", required=False)
        if named is not None and _is_text_list(f.get("sessions")):
            errors += [f"{name}.sessions: {s} is not in sources.sessions" for s in f["sessions"] if s not in named]
        if "feature" in f and "wontfix" in f:
            errors.append(f"{name}: feature and wontfix are exclusive")
    return errors


def retro_errors(retro):
    """The problems of a parsed retro.yaml, each as '<field>: <problem>'."""
    if not isinstance(retro, dict):
        return ["must be a mapping"]
    errors = []
    _field(retro, "date", lambda v: isinstance(v, date) and not isinstance(v, datetime),
           "must be a date (YYYY-MM-DD)", errors)
    for key in ("title", "summary"):
        _field(retro, key, _is_text, "must be text", errors)
    _field(retro, "sources", lambda v: isinstance(v, dict), "must be a mapping", errors)
    if isinstance(retro.get("sources"), dict):
        _field(retro["sources"], "sessions", lambda v: _is_text_list(v) and v, "must be a list of session ids",
               errors, "sources.sessions")
    named = _sources(retro)
    errors += [f"sources.sessions: {s} named twice" for s in _twice(named or [])]
    _field(retro, "findings", lambda v: isinstance(v, list), "must be a list", errors)
    _field(retro, "decisions", _is_text_list, "must be a list of text", errors)
    _field(retro, "outcome", _is_text, "must be text", errors, required=False)
    if isinstance(retro.get("findings"), list):
        errors += finding_errors(retro["findings"], named)
    return errors


def session_errors(named, digests):
    """Sessions digested twice; then, when the sources are usable, ids missing from either side."""
    if not isinstance(digests, list) or not all(isinstance(d, dict) and _is_text(d.get("session")) for d in digests):
        return ["must be a list of digests"]
    digested = [d["session"] for d in digests]
    errors = [f"{s}: digested twice" for s in _twice(digested)]
    if named is not None:
        errors += ([f"{s}: named in sources.sessions but not digested" for s in named if s not in digested]
                   + [f"{s}: digested but not in sources.sessions" for s in digested if s not in named])
    return errors


def read_retro(folder):
    """A retro folder's retro.yaml and sessions.yaml, parsed, with every problem of both, one line each."""
    errors = []
    retro = _load(Path(folder) / "retro.yaml", errors)
    if not errors:
        errors += [f"retro.yaml: {e}" for e in retro_errors(retro)]
    loaded = len(errors)
    digests = _load(Path(folder) / "sessions.yaml", errors)
    if len(errors) == loaded:
        errors += [f"sessions.yaml: {e}" for e in session_errors(_sources(retro), digests)]
    return retro, digests, errors


def _cell(text):
    return " ".join(str(text).split()).replace("|", "\\|")


def _row(cells):
    return "| " + " | ".join(_cell(c) for c in cells) + " |"


def _fix(f):
    if "wontfix" in f:
        return f"{f['fix'].strip().rstrip('.')}. Won't fix: {f['wontfix']}"
    return f"{f['fix']} ({f['feature']})" if "feature" in f else f["fix"]


def _session_row(d):
    cost = d.get("cost_usd")
    return _row([d["session"][:8], Path(d["project"]).name if d.get("project") else "-",
                 round((d.get("duration_s") or 0) / 60), (d.get("calls") or {}).get("total", 0),
                 sum(len(v) for v in (d.get("failures") or {}).values()), len(d.get("search_streaks") or []),
                 f"${cost:.2f}" if cost is not None else "-"])


def report(retro, digests, statuses):
    """retro.md for a valid retro: Source, Findings with their statuses, Decisions, Sessions and, when written,
    Outcome."""
    lines = [GENERATED_NOTE, f"# Retro {retro['date']}: {retro['title']}", "",
             f"Source: {retro['summary'].strip()}", "", "## Findings", "",
             "| # | Category | What happened | Fix | Status |", "|---|---|---|---|---|"]
    lines += [_row([f["id"], CATEGORIES[f["category"]], f["what"], _fix(f), status])
              for f, status in zip(retro["findings"], statuses)]
    if retro["decisions"]:
        lines += ["", "## Decisions", ""] + [f"- {d}" for d in retro["decisions"]]
    lines += ["", "## Sessions", "", "| Session | Project | Minutes | Calls | Failures | Search streaks | Cost |",
              "|---|---|---|---|---|---|---|"] + [_session_row(d) for d in digests]
    if "outcome" in retro:
        lines += ["", "## Outcome", "", retro["outcome"].strip()]
    return "\n".join(lines) + "\n"


def load_config(path):
    """retros and projects from config.yaml, ~ expanded, with one line per problem."""
    errors = []
    cfg = _load(path, errors)
    if not errors:
        if not isinstance(cfg, dict):
            errors.append("must be a mapping")
        else:
            _field(cfg, "retros", _is_text, "must be a path", errors)
            _field(cfg, "projects", lambda v: _is_text_list(v) and v, "must be a list of paths", errors)
    if errors:
        return None, [f"{path}: {e.removeprefix(path.name + ': ')}; see config.example.yaml" for e in errors]
    return {"retros": Path(cfg["retros"]).expanduser(),
            "projects": [Path(p).expanduser() for p in cfg["projects"]]}, []


def read_retros(cfg):
    """Every retro folder under retros, parsed; its validate errors prefixed by the folder name."""
    retros, errors = [], []
    for folder in sorted(p.parent for p in cfg["retros"].glob("*/retro.yaml")):
        retro, _, problems = read_retro(folder)
        errors += [f"{folder.name}: {e}" for e in problems]
        retros.append((folder, retro))
    return retros, errors


def session_folder(project):
    """The folder Claude Code keeps a project's session logs in: its path with each non-alphanumeric as '-'."""
    return re.sub(r"[^A-Za-z0-9]", "-", str(project))


def pending_logs(cfg, retros):
    """Top-level session logs of the configured projects and their subfolders, oldest first, minus the sessions
    a retro names and the session in progress."""
    used = {s for _, retro in retros for s in retro["sources"]["sessions"]}
    used.add(os.environ.get("CLAUDE_CODE_SESSION_ID"))
    names = [session_folder(p) for p in cfg["projects"]]
    folders = [f for f in (Path.home() / ".claude" / "projects").glob("*")
               if any(f.name == n or f.name.startswith(n + "-") for n in names)]
    logs = [log for f in folders for log in f.glob("*.jsonl") if log.stem not in used]
    return sorted(logs, key=lambda log: log.stat().st_mtime)


def finding_statuses(folder, findings):
    """Each finding's status, read from the retro's roadmap.yaml and the feature.yaml files under features/:
    wontfix, open (no feature), fixed (its feature is done) or planned."""
    errors = []
    roadmap = _load(folder / "roadmap.yaml", errors) if (folder / "roadmap.yaml").is_file() else {}
    listed = {f.get("id") for m in (roadmap or {}).get("milestones") or [] for f in m.get("features") or []}
    done = set()
    for path in folder.glob("features/*/feature.yaml"):
        feature = yaml.safe_load(path.read_text())
        if isinstance(feature, dict) and feature.get("status") == "done":
            done.add(feature.get("roadmap"))
    statuses = []
    for f in findings:
        if "wontfix" in f:
            statuses.append("wontfix")
        elif "feature" not in f:
            statuses.append("open")
        elif f["feature"] in done:
            statuses.append("fixed")
        else:
            statuses.append("planned")
            if f["feature"] not in listed:
                errors.append(f"findings[{f['id']}]: {f['feature']} is not in roadmap.yaml")
    return statuses, errors


def check(retros, show_all):
    """Lines for the findings still to do (every finding with show_all) and a closing count; and the errors."""
    lines, errors, count = [], [], Counter()
    for folder, retro in retros:
        statuses, problems = finding_statuses(folder, retro["findings"])
        errors += [f"{folder.name}: {e}" for e in problems]
        for f, status in zip(retro["findings"], statuses):
            count[status] += 1
            if show_all or status in ("open", "planned"):
                lines.append(f"{folder.name} #{f['id']} {status}: {_fix(f)}")
    lines.append(f"{count['open'] + count['planned']} to do; {count['fixed']} fixed, {count['wontfix']} won't fix")
    return lines, errors


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", type=Path, default=Path(__file__).resolve().parent.parent / "config.yaml",
                        help="config.yaml to read (default: the one beside SKILL.md)")
    sub = parser.add_subparsers(dest="cmd", required=True)
    d = sub.add_parser("digest", help="digest Claude Code session logs, in the order given")
    d.add_argument("logs", nargs="+")
    v = sub.add_parser("validate", help="check a retro folder's retro.yaml and sessions.yaml")
    v.add_argument("folder")
    r = sub.add_parser("render", help="write a valid retro folder's retro.md")
    r.add_argument("folder")
    sub.add_parser("pending", help="list the session logs no retro has read, oldest first")
    c = sub.add_parser("check", help="list the findings of every retro still to fix")
    c.add_argument("--all", action="store_true", help="also list the fixed and wontfix findings")
    args = parser.parse_args(argv)

    if args.cmd == "digest":
        try:
            result = [digest(log) for log in args.logs]
        except NotASessionLog as e:
            print(f"{e} is not a Claude Code session log", file=sys.stderr)
            return 1
        print(yaml.safe_dump(result, sort_keys=False, allow_unicode=True, width=200), end="")
        return 0
    if args.cmd in ("pending", "check"):
        cfg, errors = load_config(args.config)
        retros, more = read_retros(cfg) if cfg else ([], [])
        for e in errors + more:
            print(e, file=sys.stderr)
        if errors or more:
            return 1
        if args.cmd == "pending":
            lines = [str(log) for log in pending_logs(cfg, retros)]
        else:
            lines, errors = check(retros, args.all)
            for e in errors:
                print(e, file=sys.stderr)
            if errors:
                return 1
        for line in lines:
            print(line)
        return 0
    retro, digests, errors = read_retro(args.folder)
    for e in errors:
        print(e, file=sys.stderr)
    if errors:
        return 1
    if args.cmd == "validate":
        print(f"{args.folder} OK")
        return 0
    folder = Path(args.folder)
    statuses, errors = finding_statuses(folder, retro["findings"])
    for e in errors:
        print(e, file=sys.stderr)
    if errors:
        return 1
    (folder / "retro.md").write_text(report(retro, digests, statuses))
    print(f"wrote {folder / 'retro.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
